def evidence_note(codes: list[str], minutes: int) -> str:
    """A plain description of how one activity relates to its research bases."""
    approaches = [RESEARCH_BASES[code]["approach"].lower() for code in codes]
    joined = approaches[0] if len(approaches) == 1 else ", ".join(approaches[:-1]) + " and " + approaches[-1]
    return (
        f"Adapted from research on {joined}. That research looked at broader programs or "
        f"patterns; this {minutes}-minute suggestion was not itself tested."
    )


def activities() -> list[dict]:
    """Every activity in catalog order, with its category and sort_order."""
    rows = []
    for category, entries in CATALOG.items():
        for slug, energy, minutes, codes, moves, title, instructions, why in entries:
            code_list = codes.split(",")
            rows.append({
                "slug": slug,
                "category": category,
                "energy_level": energy,
                "duration_minutes": minutes,
                "research_codes": code_list,
                "involves_movement": moves,
                "title": title,
                "instructions": instructions,
                "why_it_fits": why,
                "evidence_note": evidence_note(code_list, minutes),
                "sort_order": len(rows) + 1,
            })
    return rows
