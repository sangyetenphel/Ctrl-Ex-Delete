-- 001: The whole CED schema, for a new, empty database (docs/DATABASE_DESIGN.md).
--
-- Schema only: the shared catalogs (activities and their research, the
-- categories, affirmations, room messages) come from the seed scripts that
-- `python -m scripts.migrate` runs afterwards. User tables start empty.
--
-- It replaces the 19 earlier migrations (db/migrations/legacy/, kept for
-- reference). scripts.migrate refuses a database that has that older history.
--
-- Conventions: user data hangs off installations and is deleted with it
-- (ON DELETE CASCADE); a user row may only point at rows of the same
-- installation (composite foreign keys on (id, installation_id)); catalog rows
-- are never deleted while user history points at them (retired with is_active).

-- ─────────────────────────────────────────────
-- Catalogs
-- ─────────────────────────────────────────────

CREATE TABLE activity_categories (
    category    TEXT PRIMARY KEY
                CHECK (category IN ('outdoor_movement', 'mindfulness_rest', 'solo_exploration', 'social_connection')),
    label       TEXT NOT NULL UNIQUE,      -- shown in the app, e.g. "Outdoor & Movement"
    sort_order  SMALLINT NOT NULL
);

CREATE TABLE activities (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug               TEXT NOT NULL UNIQUE,     -- stable id from scripts/catalog_data.py
    title              TEXT NOT NULL,
    category           TEXT NOT NULL REFERENCES activity_categories (category) ON UPDATE CASCADE,
    energy_level       TEXT NOT NULL CHECK (energy_level IN ('low', 'medium', 'high')),
    involves_movement  BOOLEAN NOT NULL DEFAULT FALSE,
    duration_minutes   SMALLINT NOT NULL CHECK (duration_minutes > 0),
    instructions       TEXT NOT NULL,
    why_it_fits        TEXT NOT NULL,
    evidence_note      TEXT,
    sort_order         SMALLINT NOT NULL DEFAULT 0,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE research_bases (
    code            TEXT PRIMARY KEY CHECK (code ~ '^[A-Z]$'),
    approach        TEXT NOT NULL,
    citation        TEXT NOT NULL,
    url             TEXT NOT NULL,
    evidence_scope  TEXT NOT NULL
);

CREATE TABLE activity_research_bases (
    activity_id  INTEGER NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
    code         TEXT NOT NULL REFERENCES research_bases (code),
    PRIMARY KEY (activity_id, code)
);

CREATE TABLE affirmation_themes (
    code        TEXT PRIMARY KEY,
    label       TEXT NOT NULL,
    sort_order  INTEGER NOT NULL
);

CREATE TABLE affirmations (
    id          TEXT PRIMARY KEY,
    text        TEXT NOT NULL CHECK (char_length(text) BETWEEN 3 AND 120),
    theme       TEXT NOT NULL REFERENCES affirmation_themes (code),
    language    TEXT NOT NULL DEFAULT 'en',
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (language, text)
);

CREATE TABLE affirmation_sources (
    code         TEXT PRIMARY KEY,
    citation     TEXT NOT NULL,
    url          TEXT NOT NULL,
    kind         TEXT NOT NULL CHECK (kind IN ('values_self_affirmation', 'positive_self_statements', 'self_compassion',
                                               'breakup_research', 'acceptance', 'self_efficacy')),
    finding      TEXT NOT NULL,
    limitations  TEXT NOT NULL
);

CREATE TABLE affirmation_theme_sources (
    theme        TEXT NOT NULL REFERENCES affirmation_themes (code),
    source_code  TEXT NOT NULL REFERENCES affirmation_sources (code),
    principle    TEXT NOT NULL,
    rationale    TEXT NOT NULL,
    PRIMARY KEY (theme, source_code)
);

CREATE TABLE affirmation_notes (
    affirmation_id  TEXT PRIMARY KEY REFERENCES affirmations (id),
    note            TEXT NOT NULL
);

CREATE TABLE room_messages (
    id          TEXT PRIMARY KEY,
    pattern     TEXT NOT NULL CHECK (pattern IN ('before_check_in', 'strong_urge', 'heavy_low_energy', 'low_energy',
                                                 'lonely', 'heavy_some_energy', 'lighter_with_energy', 'general')),
    text        TEXT NOT NULL CHECK (char_length(text) BETWEEN 10 AND 110),
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ─────────────────────────────────────────────
-- User data
-- ─────────────────────────────────────────────

CREATE TABLE installations (
    id            UUID PRIMARY KEY,                       -- the app's Keychain UUID (X-Installation-ID)
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now()      -- day precision: updated at most once a day
);

CREATE TABLE check_ins (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id  UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    local_date       DATE NOT NULL,                        -- the user's own calendar day
    feeling          TEXT NOT NULL CHECK (feeling IN ('heavy', 'getting_through', 'missing_them', 'hopeful')),
    contact_urge     SMALLINT NOT NULL CHECK (contact_urge BETWEEN 1 AND 10),
    energy_level     TEXT NOT NULL CHECK (energy_level IN ('low', 'medium', 'high')),
    hardest_areas    TEXT[] NOT NULL DEFAULT '{}'
                     CHECK (hardest_areas <@ ARRAY['feeling_lonely', 'missing_relationship', 'wanting_answers',
                                                   'resisting_contact', 'rebuilding_confidence']
                            AND cardinality(hardest_areas) <= 5),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (installation_id, local_date),                  -- one check-in per day
    UNIQUE (id, installation_id)                           -- target of "same installation" keys
);

CREATE TABLE recommendations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id  UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    check_in_id      BIGINT NOT NULL,
    activity_id      INTEGER NOT NULL REFERENCES activities (id),
    position         SMALLINT NOT NULL CHECK (position >= 1),
    FOREIGN KEY (check_in_id, installation_id) REFERENCES check_ins (id, installation_id) ON DELETE CASCADE,
    UNIQUE (check_in_id, position),
    UNIQUE (check_in_id, activity_id),
    UNIQUE (id, installation_id)
);
CREATE INDEX idx_recommendations_install ON recommendations (installation_id, check_in_id);
CREATE INDEX idx_recommendations_activity ON recommendations (activity_id);   -- catalog retire/delete checks

CREATE TABLE activity_selections (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id    UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    recommendation_id  BIGINT NOT NULL,
    selected_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    status             TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed', 'abandoned')),
    ended_at           TIMESTAMPTZ,
    completed_on       DATE,                               -- the user's calendar day it was completed
    FOREIGN KEY (recommendation_id, installation_id) REFERENCES recommendations (id, installation_id) ON DELETE CASCADE,
    CHECK ((status = 'in_progress') = (ended_at IS NULL)),
    CHECK ((status = 'completed') = (completed_on IS NOT NULL)),
    UNIQUE (id, installation_id)
);
CREATE INDEX idx_activity_selections_install ON activity_selections (installation_id);
CREATE INDEX idx_activity_selections_completed_on ON activity_selections (installation_id, completed_on)
    WHERE status = 'completed';
-- One activity in progress per installation, and one live (not abandoned) choice per card.
CREATE UNIQUE INDEX activity_selections_one_in_progress ON activity_selections (installation_id)
    WHERE status = 'in_progress';
CREATE UNIQUE INDEX activity_selections_one_live_per_recommendation ON activity_selections (recommendation_id)
    WHERE status <> 'abandoned';

CREATE TABLE scrapbook_photos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id  UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    object_key       TEXT NOT NULL UNIQUE,                 -- the file's key in the S3 bucket
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    uploaded_at      TIMESTAMPTZ,                          -- NULL until the upload is confirmed
    UNIQUE (id, installation_id)
);
CREATE INDEX idx_scrapbook_photos_install ON scrapbook_photos (installation_id, created_at DESC);

CREATE TABLE reflections (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id        UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    activity_selection_id  BIGINT UNIQUE,
    photo_id               BIGINT UNIQUE,
    note                   TEXT CHECK (char_length(note) <= 1000),          -- "What did you notice?"
    thought_about_ex       TEXT CHECK (thought_about_ex IN ('not_really', 'a_little', 'a_lot')),
    mood_change            TEXT CHECK (mood_change IN ('worse', 'about_the_same', 'a_little_better', 'much_better')),
    local_date             DATE NOT NULL,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- The memory outlives its activity choice or photo: only the link is cleared.
    FOREIGN KEY (activity_selection_id, installation_id) REFERENCES activity_selections (id, installation_id)
        ON DELETE SET NULL (activity_selection_id),
    FOREIGN KEY (photo_id, installation_id) REFERENCES scrapbook_photos (id, installation_id)
        ON DELETE SET NULL (photo_id)
);
CREATE INDEX idx_reflections_install_created ON reflections (installation_id, created_at DESC);
CREATE INDEX idx_reflections_install_local_date ON reflections (installation_id, local_date);

CREATE TABLE activity_bookmarks (
    installation_id  UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    activity_id      INTEGER NOT NULL REFERENCES activities (id) ON DELETE CASCADE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (installation_id, activity_id)
);
CREATE INDEX idx_activity_bookmarks_activity ON activity_bookmarks (activity_id);   -- catalog retire/delete checks

CREATE TABLE check_in_room_messages (
    check_in_id  BIGINT PRIMARY KEY REFERENCES check_ins (id) ON DELETE CASCADE,
    message_id   TEXT NOT NULL REFERENCES room_messages (id),
    -- Kept as shown, so a later catalog edit never changes a past day's message.
    pattern      TEXT NOT NULL,
    text         TEXT NOT NULL,
    assigned_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE moving_forward_check_ins (
    installation_id   UUID PRIMARY KEY REFERENCES installations (id) ON DELETE CASCADE,
    moved_forward_on  DATE NOT NULL,                       -- the day they first chose it
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
    -- No answers stored: saving requires all five readiness questions (the API checks it).
);

CREATE TABLE ced_usage (
    installation_id  UUID NOT NULL REFERENCES installations (id) ON DELETE CASCADE,
    usage_date       DATE NOT NULL,                        -- UTC day
    messages         INTEGER NOT NULL DEFAULT 0 CHECK (messages >= 0),
    PRIMARY KEY (installation_id, usage_date)
    -- Only a count: conversation text is never stored (app/ced/).
);
